import type { KeywordGroup, Question, Variant } from "@/lib/types";

function q(id: string, prompt: string, explanation: string, statement: string, answer: boolean, options: string[], answerIndex: number, accepted: string[], hint: string, keywords?: KeywordGroup[]): Question {
  const variants: Variant[] = [
    { type: "true_false", points: 5, statement, answer },
    { type: "choice", points: 10, options, answerIndex },
    { type: "short", points: 20, accepted, hint, ...(keywords ? { keywords } : {}) },
  ];
  return { id, prompt, explanation, variants };
}

